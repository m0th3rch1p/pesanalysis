#!/usr/bin/env bash
# Build the submission-only public snapshot from this private repository.
# Nothing is pushed. The founder reviews the output and creates the new repo.
#
#   tools/export-public.sh /tmp/pesanalysis-public
#
# Requires: tools/private-denylist.txt (untracked; one literal string per line, e.g. real names,
# references, account numbers, the phone serial). The script refuses secrets and PII it can detect.
set -euo pipefail
SRC="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${1:?usage: export-public.sh <empty-output-dir>}"
DENY="$SRC/tools/private-denylist.txt"
[ -d "$OUT" ] && [ -n "$(ls -A "$OUT")" ] && { echo "output dir must be empty"; exit 2; }
mkdir -p "$OUT"

# 1. Allowlist copy (source, build inputs, docs; never data/private, _private, legal, build outputs).
rsync -a \
  --exclude node_modules --exclude .git --exclude 'android/app/build' --exclude 'android/.gradle' \
  --exclude 'apps/mobile/android/build' --exclude 'apps/mobile/modules/*/android/build' \
  --exclude 'apps/mobile/qvac/worker.bundle.js' --exclude 'apps/mobile/.expo' \
  --exclude 'data/private' --exclude 'docs/plan/_private' --exclude 'docs/legal' \
  --exclude 'tools/private-denylist.txt' --exclude '*.keystore' --exclude '*.jks' \
  --exclude '.claude' --exclude 'apps/mobile/android/local.properties' \
  "$SRC"/ "$OUT"/

# 2. Replace real fixture strings with synthetic equivalents (mapping file: "real<TAB>synthetic").
if [ -f "$SRC/tools/private-map.tsv" ]; then
  while IFS=$'\t' read -r from to; do
    [ -z "${from:-}" ] && continue
    grep -rIl --exclude-dir=.git -F "$from" "$OUT" | while read -r f; do
      python3 - "$f" "$from" "$to" <<'PY'
import sys
p,a,b=sys.argv[1],sys.argv[2],sys.argv[3]
s=open(p,encoding="utf-8",errors="ignore").read()
open(p,"w",encoding="utf-8").write(s.replace(a,b))
PY
    done
  done < "$SRC/tools/private-map.tsv"
fi

# 3. Scans. Any hit stops the export.
status=0
if [ -f "$DENY" ]; then
  # Case-insensitive whole-word scan: "Wiki" must not match "wikipedia" or Swahili "wiki hii".
  python3 - "$DENY" "$OUT" <<'PYDENY'
import re, sys, pathlib
deny = pathlib.Path(sys.argv[1]); root = pathlib.Path(sys.argv[2])
terms = [ln.strip() for ln in deny.read_text(encoding="utf-8").splitlines() if ln.strip()]
pats = [(t, re.compile(r"(?<![0-9A-Za-z])" + re.escape(t) + r"(?![0-9A-Za-z])", re.I)) for t in terms]
skip = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".apk", ".so", ".a", ".zip", ".jar", ".gguf", ".ttf", ".otf"}
bad = 0
for path in root.rglob("*"):
    if not path.is_file() or ".git" in path.parts: continue
    if path.suffix.lower() in skip: continue
    try: text = path.read_text(encoding="utf-8", errors="ignore")
    except Exception: continue
    if "\x00" in text: continue
    for term, rx in pats:
        m = rx.search(text)
        if m:
            line = text.count("\n", 0, m.start()) + 1
            print(f"{path.relative_to(root)}:{line}: DENYLIST HIT ({term})")
            bad += 1
sys.exit(1 if bad else 0)
PYDENY
  if [ $? -ne 0 ]; then status=1; echo "DENYLIST HIT(S) above"; fi
else
  echo "warning: tools/private-denylist.txt missing; only generic scans run"
fi
# generic PII/secret shapes. Synthetic fixture ranges (0700000xxx/0100000xxx, 0712345678,
# 2547XXXXXXXX) are explicit placeholders; anything else that looks like a Kenyan mobile number fails.
python3 - "$OUT" <<'PYPII'
import re, sys, pathlib
root = pathlib.Path(sys.argv[1])
phone = re.compile(r"\b0[17][0-9]{2}[ -]?[0-9]{3}[ -]?[0-9]{3}\b")
allowed = re.compile(r"^(?:0[17]0{5}[0-9]{3}|0712345678|0123456789)$")
secret = re.compile(r"AKIA[0-9A-Z]{16}|BEGIN [A-Z ]*PRIVATE KEY|\bsk-[A-Za-z0-9]{20,}")
bad = 0
for path in root.rglob("*"):
    if not path.is_file() or ".git" in path.parts or path.name == "package-lock.json":
        continue
    if path.suffix.lower() in {".png", ".jpg", ".jpeg", ".gif", ".webp", ".apk", ".so", ".a", ".zip", ".jar", ".gguf", ".ttf", ".otf"}:
        continue
    try:
        text = path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        continue
    if "\x00" in text:
        continue
    for i, line in enumerate(text.splitlines(), 1):
        nums = [re.sub(r"[ -]", "", m.group(0)) for m in phone.finditer(line)]
        if any(not allowed.match(n) for n in nums) or secret.search(line):
            print(f"{path.relative_to(root)}:{i}:{line[:180]}")
            bad += 1
sys.exit(1 if bad else 0)
PYPII
if [ $? -ne 0 ]; then echo "GENERIC PII/SECRET HIT"; status=1; fi

[ "$status" -eq 0 ] || { echo "Export failed checks. Nothing was committed."; exit 1; }

cat > "$OUT/EXPORT_README.txt" <<'TXT'
This snapshot was generated by tools/export-public.sh from the private repository.
Before publishing:
  1. Fill in README "What existed before the event" and the QVAC section (docs/QVAC_INTEGRATION.md).
  2. Review every file for personal data one last time (the automated scan is a backstop, not proof).
  3. Run: npm ci --ignore-scripts && npm test && npx tsc --noEmit -p packages/core
  4. Create the public repository, commit once, add team members to the DoraHacks Build.
TXT
echo "OK: snapshot at $OUT (scans clean)."
